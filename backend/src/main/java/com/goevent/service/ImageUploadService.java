package com.goevent.service;

import com.goevent.config.FileStorageConfig;
import com.goevent.config.FileStorageConfig.StorageSettings;
import com.goevent.exception.ImageException;
import com.goevent.util.AppUtil;
import org.slf4j.Logger;
import org.springframework.core.io.FileSystemResource;
import org.springframework.core.io.Resource;
import org.springframework.http.HttpStatus;
import org.springframework.stereotype.Service;
import org.springframework.web.multipart.MultipartFile;

import java.io.IOException;
import java.io.InputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Optional;
import java.util.UUID;
import java.util.regex.Pattern;

/**
 * Every image file operation for the platform: validate, store, serve and
 * delete. Feature services call this class and persist the returned URL in
 * MySQL; nothing else touches the image filesystem.
 *
 * <p>Files are grouped per owner ({@code profile/13/<uuid>.png}) so an owner's
 * images can be removed as a unit. Location, accepted formats and size limits
 * come from {@link FileStorageConfig}.</p>
 */
@Service
public class ImageUploadService {

    private static final Logger logger = AppUtil.getLogger(ImageUploadService.class);

    private static final int MAGIC_HEADER_BYTES = 12;

    /** Names generated by this service: a UUID plus the detected extension. */
    private static final Pattern MANAGED_FILENAME = Pattern.compile(
            "^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\\.(jpg|png|webp)$"
    );

    /** Owners are database ids; this also blocks any path traversal attempt. */
    private static final Pattern OWNER = Pattern.compile("^\\d{1,10}$");

    private final StorageSettings settings;

    public ImageUploadService(StorageSettings settings) {
        this.settings = settings;
    }

    private record DetectedImage(String extension, String contentType) {
    }

    // --- storing --------------------------------------------------------

    public String uploadProfilePicture(int userId, MultipartFile file) {
        return store(FileStorageConfig.SCOPE_PROFILE, userId, file);
    }

    public String uploadEventImage(int eventId, MultipartFile file) {
        return store(FileStorageConfig.SCOPE_EVENT, eventId, file);
    }

    public String uploadEventBanner(int eventId, MultipartFile file) {
        return store(FileStorageConfig.SCOPE_BANNER, eventId, file);
    }

    /** Validates and stores an image, then returns the public URL to persist. */
    public String store(String scope, int ownerId, MultipartFile file) {

        DetectedImage image = validate(scope, file);

        String owner = Integer.toString(ownerId);
        String filename = UUID.randomUUID() + "." + image.extension();
        Path directory = directory(scope, owner);

        try {
            Files.createDirectories(directory);

            try (InputStream input = file.getInputStream()) {
                // No REPLACE_EXISTING: a UUID clash must fail, not overwrite.
                Files.copy(input, directory.resolve(filename));
            }
        } catch (IOException e) {
            try {
                Files.deleteIfExists(directory.resolve(filename));
            } catch (IOException cleanupFailure) {
                logger.warn("Could not clean up a partially written image: {}", filename);
            }

            logger.error("Failed to store a {} image ({} bytes) in {}",
                    scope, file.getSize(), directory, e);

            throw new ImageException(HttpStatus.INTERNAL_SERVER_ERROR,
                    "Could not save the image. Please try again.");
        }

        logger.info("Stored {} image in {} ({} bytes)", scope, directory, file.getSize());

        return settings.publicPath(scope, owner, filename);
    }

    /** Validates format and size without storing anything. */
    public void validateImage(String scope, MultipartFile file) {
        validate(scope, file);
    }

    // --- serving and deleting -------------------------------------------

    /** Loads an image for the public read endpoint; empty for anything invalid. */
    public Optional<Resource> load(String scope, String owner, String filename) {

        if (!isManaged(scope, owner, filename)) {
            return Optional.empty();
        }

        Path target = path(scope, owner, filename);

        return target.startsWith(settings.root()) && Files.isRegularFile(target)
                ? Optional.of(new FileSystemResource(target))
                : Optional.empty();
    }

    public boolean deleteImage(String scope, String owner, String filename) {

        if (!isManaged(scope, owner, filename)) {
            return false;
        }

        Path target = path(scope, owner, filename);

        if (!target.startsWith(settings.root())) {
            return false;
        }

        try {
            boolean deleted = Files.deleteIfExists(target);

            if (deleted) {
                logger.info("Deleted {} image {}", scope, target);
            }

            return deleted;
        } catch (IOException e) {
            logger.error("Failed to delete {} image {}", scope, target, e);
            return false;
        }
    }

    /**
     * Deletes the file behind a stored URL. External URLs (for example Google
     * avatars) and unmanaged paths are ignored.
     */
    public boolean deleteByPath(String scope, String storedUrl) {

        String[] location = parseUrl(scope, storedUrl);

        return location != null && deleteImage(scope, location[0], location[1]);
    }

    /** True when a URL points at an image stored under exactly this scope. */
    public boolean isManagedUrl(String scope, String url) {
        return parseUrl(scope, url) != null;
    }

    // --- validation -----------------------------------------------------

    private DetectedImage validate(String scope, MultipartFile file) {

        if (file == null || file.isEmpty()) {
            throw new ImageException(HttpStatus.BAD_REQUEST, "Please choose an image file");
        }

        if (file.getSize() > settings.maxSizeBytes(scope)) {
            throw new ImageException(HttpStatus.BAD_REQUEST,
                    "Image must be " + settings.maxSizeLabel(scope) + " or smaller");
        }

        DetectedImage image = detect(file);

        if (image == null || !FileStorageConfig.ALLOWED_CONTENT_TYPES.contains(image.contentType())) {
            throw new ImageException(HttpStatus.BAD_REQUEST,
                    "Only JPEG, PNG or WebP images are supported");
        }

        logger.debug("Accepted {} image: {} bytes, {}", scope, file.getSize(), image.contentType());

        return image;
    }

    /** Detects the real format from magic bytes; the client name is never trusted. */
    private DetectedImage detect(MultipartFile file) {

        try (InputStream input = file.getInputStream()) {
            byte[] header = input.readNBytes(MAGIC_HEADER_BYTES);

            if (isJpeg(header)) {
                return new DetectedImage("jpg", "image/jpeg");
            }

            if (isPng(header)) {
                return new DetectedImage("png", "image/png");
            }

            if (isWebp(header)) {
                return new DetectedImage("webp", "image/webp");
            }
        } catch (IOException e) {
            logger.warn("Could not inspect an uploaded image header: {}", e.getMessage());
        }

        return null;
    }

    private boolean isJpeg(byte[] header) {
        return header.length >= 3
                && (header[0] & 0xFF) == 0xFF
                && (header[1] & 0xFF) == 0xD8
                && (header[2] & 0xFF) == 0xFF;
    }

    private boolean isPng(byte[] header) {
        return header.length >= 8
                && (header[0] & 0xFF) == 0x89
                && header[1] == 'P'
                && header[2] == 'N'
                && header[3] == 'G'
                && header[4] == 0x0D
                && header[5] == 0x0A
                && header[6] == 0x1A
                && header[7] == 0x0A;
    }

    private boolean isWebp(byte[] header) {
        return header.length >= MAGIC_HEADER_BYTES
                && header[0] == 'R'
                && header[1] == 'I'
                && header[2] == 'F'
                && header[3] == 'F'
                && header[8] == 'W'
                && header[9] == 'E'
                && header[10] == 'B'
                && header[11] == 'P';
    }

    // --- paths ----------------------------------------------------------

    private boolean isManaged(String scope, String owner, String filename) {
        return settings.isScope(scope)
                && owner != null && OWNER.matcher(owner).matches()
                && filename != null && MANAGED_FILENAME.matcher(filename).matches();
    }

    private Path directory(String scope, String owner) {

        Path directory = settings.root().resolve(scope).resolve(owner).normalize();

        if (!directory.startsWith(settings.root())) {
            throw new ImageException(HttpStatus.INTERNAL_SERVER_ERROR,
                    "Could not resolve the image storage location");
        }

        return directory;
    }

    private Path path(String scope, String owner, String filename) {
        return directory(scope, owner).resolve(filename).normalize();
    }

    /** Splits a stored URL into {owner, filename}, or null when it is not ours. */
    private String[] parseUrl(String scope, String url) {

        if (!settings.isScope(scope) || url == null || url.isBlank()) {
            return null;
        }

        String prefix = settings.publicScopePrefix(scope);

        if (!url.startsWith(prefix)) {
            return null;
        }

        String[] parts = url.substring(prefix.length()).split("/");

        return parts.length == 2 && isManaged(scope, parts[0], parts[1]) ? parts : null;
    }
}